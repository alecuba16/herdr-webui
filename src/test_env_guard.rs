//! Guard for the test env-lock convention (PR #240 follow-up).
//!
//! Env vars are process-global and cargo test binaries run tests on parallel
//! threads, so any test that writes env vars must serialize against a shared
//! lock: `crate::tests::env_lock` (bin target) or `crate::test_env_lock`
//! (lib target), usually via a module-local wrapper fn. PR #240 unified the
//! last private lock islands after a first-build 3-test flake. This module
//! keeps that convention from regressing: it runs as a normal `#[test]`, so
//! `cargo test` (locally and in CI) enforces it on every change.
//!
//! How it works: every `src/**/*.rs`, `tests/**/*.rs`, and `build.rs` file is
//! parsed with syn (AST, so string literals and comments never trip it) and
//! the rules below are checked.
//!
//! R1 - every fn whose body calls something named `set_var`/`remove_var` must
//! also acquire a lock named `env_lock`/`lock_env`/`home_lock`/
//! `test_env_lock` within the same fn body (closures inside the body count,
//! e.g. the spawn_blocking env redirect in the composer parity e2e). Fns that
//! legitimately cannot take the lock (helpers running under the caller's
//! guard, evidence-verified race-free tests, runtime code) live in
//! `ALLOWLIST` with written evidence.
//!
//! R3 - no static unit mutex (`Mutex<()>`, including `OnceLock<Mutex<()>>`)
//! may exist outside the allowed lock fns, and an allowed lock fn may own
//! exactly one such static. In `src/` the only allowed owners are the two
//! canonical lock factories; in `tests/` each integration binary owns one
//! lock convention of its own, so a fn whose name is in `LOCK_NAMES` may own
//! one (at most one per file: two islands in the same binary can race). A
//! private island lets its holder race every other module's env window in
//! the same test binary, which is exactly the PR #240 bug class, so R3 bans
//! the island itself rather than trusting wrapper fns to point at a
//! canonical lock.
//!
//! Stale entries: an `ALLOWLIST` entry that no longer matches a real
//! env-writing fn fails the guard, so the evidence cannot silently rot.
//!
//! R1 coverage is order- and scope-sensitive: the lock must be acquired
//! before the first env write, in the same closure scope. A lock guard
//! taken in a fn body does not cover env writes inside closures or async
//! blocks in it (spawned threads and deferred closures can outlive the
//! guard), and a write before the lock call races the window between fn
//! start and acquisition. Closures that write env must take the lock in
//! their own body; a closure defined before the lock and called after it
//! is covered only via the allowlist (flow-insensitive residual FP).
//! Locks inside conditionally-executed blocks (`if`/`match` arms) still
//! cover later writes syntactically: the approximation is order-sensitive,
//! not flow-sensitive (same residual as before, unchanged in class).
//!
//! Known blind spots, accepted as residual risk:
//! - A `use crate::tests::*;` glob import brings `env_lock` in unqualified,
//!   and glob-import recording is out of scope for the resolver, so the
//!   call stays unprovable and fires R1 even when genuine. No real code
//!   glob-imports the tests module; spell the path out or allowlist.
//! - Env writes generated by macros are token streams that syn does not
//!   expand, so they are invisible here. No such writes exist today; every
//!   current write is a direct call.
//! - Method-call lock acquisition resolves the receiver only for plain
//!   shapes (`self`, a local bound to a unit-struct constructor). Any other
//!   receiver (field, call result, re-binding) is unprovable and fires R1;
//!   real code uses plain wrapper-fn calls, so no allowlist entry is needed.
//! - Cross-process writes (a spawned server process or another test binary
//!   reading env while a test mutates it) cannot be serialized by any
//!   in-process mutex. No such race has ever been observed in this repo; the
//!   fix would be per-process env isolation (passing env explicitly to
//!   spawned servers or serializing whole binaries), out of scope here.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use syn::visit::Visit;
use syn::{Expr, ExprCall, File, Item, ItemFn};

/// Call names that count as acquiring the shared env lock.
const LOCK_NAMES: [&str; 4] = ["env_lock", "lock_env", "home_lock", "test_env_lock"];

/// Name shapes that count as an env write: `std::env::set_var`, a bare
/// `set_var`, a `use std::env::set_var` import called bare, or the same
/// bound to a local (`let write = std::env::set_var;`). A rename
/// (`use std::env::set_var as sv`) makes the call invisible, so any rename
/// of an env-write import is itself refused: the convention is plain names.
const ENV_WRITE_NAMES: [&str; 2] = ["set_var", "remove_var"];

